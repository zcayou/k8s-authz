package engine

import (
	"fmt"
	"strings"

	"github.com/zcayou/k8s-authz/internal/compiler"
	"github.com/zcayou/k8s-authz/internal/model"
)

// fixedDimensions are the diagram dimensions other than selector keys.
var fixedDimensions = []string{model.Category, model.APIGroup, model.APIVersion, model.Resource, model.Verb, model.IngressNamespace, model.AffectedNamespace, model.Name, model.URL}

// traversalDepth bounds a diagram path: it branches at most once on each
// selector key and on every fixed dimension but one, since a path never
// branches on both the URL and the resource dimensions, and takes one more
// level to step onto its terminal.
var traversalDepth = len(fixedDimensions) + compiler.MaxSelectorKeys

// GenerateTraversal returns the unrolled levels of the traversal
// in assets/traversal_base.rego. Rego has no recursion, so each level calls
// the next, up to traversalDepth, and a walk that is not done by then
// is undefined.
func GenerateTraversal() []byte {
	var source strings.Builder
	source.WriteString("# Code generated by cmd/evaluator-gen. DO NOT EDIT.\n\npackage authz.evaluator.traversal\n\n")
	for level := range traversalDepth {
		next := level + 1
		recurse := fmt.Sprintf("point_%03d(diagram_id, query, next)", next)
		if next == traversalDepth {
			recurse = fmt.Sprintf("point_%03d(next)", next)
		}
		fmt.Fprintf(&source, `point_%03d(diagram_id, query, state) := state if {
	state.done
} else := result if {
	next := point_step(diagram_id, query, state)
	not next.broad
	result := %s
} else := result if {
	next := point_step(diagram_id, query, state)
	next.broad
	diagram := data.authz.state.diagrams[diagram_id]
	result := walk_%03d(diagram, query, frontier_from_point(next))
}

`, level, recurse, level)
	}
	fmt.Fprintf(&source, `point_%03d(state) := state if {
	state.done
}

`, traversalDepth)
	for level := range traversalDepth {
		next := level + 1
		recurse := fmt.Sprintf("walk_%03d(diagram, query, next)", next)
		if next == traversalDepth {
			recurse = fmt.Sprintf("walk_%03d(next)", next)
		}
		fmt.Fprintf(&source, `walk_%03d(diagram, query, state) := state if {
	state.done
} else := result if {
	next := step(diagram, query, state)
	result := %s
}

`, level, recurse)
	}
	fmt.Fprintf(&source, `walk_%03d(state) := state if {
	state.done
}
`, traversalDepth)
	return []byte(source.String())
}
